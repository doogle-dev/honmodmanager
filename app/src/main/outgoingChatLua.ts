// Ctrl+Enter in one of the game's own chat boxes hands the typed line to the manager instead of
// sending it, to the channel the box is in. Ctrl+Shift+Enter sends it to all chat, matching
// Shift+Enter in the game. The box clears at once like a normal send, the manager translates the
// line and writes it back through an inbox, and the game sends the translated text. The game keeps
// each line until that happens, and sends it as typed if the manager has not answered in time (the
// manager closed, or every provider is slow), so a line is never lost.
//
// There are two chat boxes. The in-match box sends through GameChat:ChatCommand in chat.lua, and
// the main menu box (chat channels such as Global, the pre-match lobby and hero pick) sends through
// Communicator:SendChat in communicator.lua. Each line's id starts with the box it came from, g or
// l, so the manager can write the send back into the inbox that side of the game polls.
//
// A line typed in a chat channel is held with the channel's name, and the game sends the
// translation back to that channel itself, so the manager only ever sees the kind: team, all or
// channel.
export const OUTGOING_FALLBACK_MILLISECONDS = 5000

export function outgoingChatLua(encodeFunctionName: string, decodeFunctionName: string): string {
  return [
    'ChatTranslatorOutgoingPending = ChatTranslatorOutgoingPending or {}',
    'ChatTranslatorOutgoingCounters = ChatTranslatorOutgoingCounters or {}',
    '',
    'function ChatTranslatorAnnounce(message)',
    "\tpcall(function() Echo('[HoN Mod Manager] ' .. message) end)",
    'end',
    '',
    'function ChatTranslatorModifiers()',
    '\tlocal ctrlDown = false',
    '\tlocal shiftDown = false',
    '\tpcall(function() ctrlDown = Input.IsCtrlDown() and true or false end)',
    '\tpcall(function() shiftDown = Input.IsShiftDown() and true or false end)',
    '\treturn ctrlDown, shiftDown',
    'end',
    '',
    'function ChatTranslatorHold(sourceTag, messageText, channelName, channelTarget)',
    "\tif string.find(messageText, '^%s*$') or string.find(messageText, '^%s*/') then return false end",
    '\tlocal queuedAt = GetTime()',
    '\tlocal count = (ChatTranslatorOutgoingCounters[sourceTag] or 0) + 1',
    '\tlocal outgoingId = sourceTag .. tostring(count)',
    "\tEcho('[HoN Mod Manager] HONCHATOUTGOING|' .. outgoingId .. '|' .. channelName .. '|' .. " +
      encodeFunctionName +
      '(messageText))',
    '\tChatTranslatorOutgoingCounters[sourceTag] = count',
    '\tChatTranslatorOutgoingPending[outgoingId] = { text = messageText, channel = channelName, channelTarget = channelTarget, queuedAt = queuedAt }',
    "\tif sourceTag == 'l' then ChatTranslatorLastLobbyChannel = channelTarget or 'Game' end",
    '\treturn true',
    'end',
    '',
    'function ChatTranslatorSendText(messageText, channelName, channelTarget)',
    "\tif channelName == 'channel' then",
    '\t\tChatSendMessage(messageText, channelTarget)',
    "\telseif channelName == 'team' then",
    '\t\tTeamChat(messageText)',
    '\telse',
    '\t\tAllChat(messageText)',
    '\tend',
    'end',
    '',
    'function ChatTranslatorOutgoing(inputText)',
    '\tlocal intercepted = false',
    '\tpcall(function()',
    '\t\tlocal ctrlDown, shiftDown = ChatTranslatorModifiers()',
    '\t\tif not ctrlDown then return end',
    "\t\tlocal channelName = 'team'",
    "\t\tif shiftDown or (GameChat and GameChat.lastType == 'all') then channelName = 'all' end",
    "\t\tintercepted = ChatTranslatorHold('g', tostring(inputText or ''), channelName, nil)",
    '\tend)',
    '\treturn intercepted',
    'end',
    '',
    'function ChatTranslatorLobbyOutgoing()',
    '\tlocal intercepted = false',
    '\tpcall(function()',
    '\t\tlocal ctrlDown, shiftDown = ChatTranslatorModifiers()',
    '\t\tif not ctrlDown then return end',
    "\t\tlocal channelName = 'team'",
    '\t\tlocal channelTarget = nil',
    '\t\tlocal textBox = Communicator.chatTextBox',
    "\t\tlocal messageText = tostring(textBox:GetInputLine() or '')",
    "\t\tif messageText ~= '' then",
    '\t\t\tlocal channelObject = Communicator.channelObjects[Communicator.selectedChannelId]',
    '\t\t\tif not (channelObject and channelObject.channelName) then return end',
    "\t\t\tif channelObject.channelName ~= 'Game' then",
    "\t\t\t\tchannelName = 'channel'",
    '\t\t\t\tchannelTarget = channelObject.channelName',
    '\t\t\tend',
    '\t\telse',
    '\t\t\ttextBox = Communicator.chatLobbyTextBox',
    "\t\t\tmessageText = tostring(textBox:GetInputLine() or '')",
    '\t\tend',
    "\t\tif channelName ~= 'channel' and (shiftDown or Communicator.currentChatType == Communicator.chatType.ALL_CHAT) then channelName = 'all' end",
    "\t\tif ChatTranslatorHold('l', messageText, channelName, channelTarget) then",
    "\t\t\ttextBox:SetInputLine('')",
    '\t\t\tintercepted = true',
    '\t\tend',
    '\tend)',
    '\treturn intercepted',
    'end',
    '',
    'function ChatTranslatorSend(encodedText, channelName, outgoingId)',
    '\tpcall(function()',
    '\t\tlocal messageText = ' + decodeFunctionName + '(encodedText)',
    "\t\tif messageText == '' then return end",
    '\t\tlocal channelTarget = nil',
    '\t\tif outgoingId ~= nil then',
    '\t\t\tlocal pending = ChatTranslatorOutgoingPending[outgoingId]',
    '\t\t\tif pending == nil then',
    "\t\t\t\tChatTranslatorAnnounce('HONCHATOUTGOINGLATE|' .. tostring(outgoingId))",
    '\t\t\t\treturn',
    '\t\t\tend',
    '\t\t\tChatTranslatorOutgoingPending[outgoingId] = nil',
    '\t\t\tchannelName = pending.channel',
    '\t\t\tchannelTarget = pending.channelTarget',
    '\t\tend',
    "\t\tif channelName == 'channel' and channelTarget == nil then return end",
    '\t\tChatTranslatorSendText(messageText, channelName, channelTarget)',
    "\t\tChatTranslatorAnnounce('HONCHATSENT|' .. tostring(channelName) .. '|' .. tostring(outgoingId or 0))",
    '\tend)',
    'end',
    '',
    'function ChatTranslatorNotice(encodedText, sourceTag)',
    '\tpcall(function()',
    '\t\tlocal noticeText = ' + decodeFunctionName + '(encodedText)',
    "\t\tif noticeText == '' then return end",
    "\t\tif sourceTag == 'l' then",
    "\t\t\tCommunicator:AddMessage(ChatTranslatorLastLobbyChannel or 'Game', '^458[T]^* ' .. noticeText, '', '')",
    '\t\telse',
    "\t\t\tGameChat:AllChatMessages('3', nil, '^458[T]^* ' .. noticeText, nil, nil, nil, 'false')",
    '\t\tend',
    "\t\tChatTranslatorAnnounce('HONCHATNOTICE|1')",
    '\tend)',
    'end',
    '',
    'function ChatTranslatorOutgoingWaiting()',
    '\tfor _ in pairs(ChatTranslatorOutgoingPending) do return true end',
    '\treturn false',
    'end',
    '',
    'function ChatTranslatorCheckOutgoing()',
    '\tlocal now = GetTime()',
    '\tfor outgoingId, pending in pairs(ChatTranslatorOutgoingPending) do',
    '\t\tif now < pending.queuedAt or now - pending.queuedAt >= ' + OUTGOING_FALLBACK_MILLISECONDS + ' then',
    '\t\t\tChatTranslatorOutgoingPending[outgoingId] = nil',
    '\t\t\tChatTranslatorSendText(pending.text, pending.channel, pending.channelTarget)',
    "\t\t\tChatTranslatorAnnounce('HONCHATOUTGOINGFALLBACK|' .. tostring(outgoingId))",
    '\t\tend',
    '\tend',
    'end',
    ''
  ].join('\n')
}
