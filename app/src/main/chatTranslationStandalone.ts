import type { ExtraFileAddition, ExtraFileEdit } from './honmodApplier'

const STANDALONE_SCRIPT_PATH = 'ui/scripts/shared/chat_translator_standalone.lua'

const STANDALONE_SCRIPT_LINES = [
  'ChatTranslatorStandalone = ChatTranslatorStandalone or {}',
  'local translator = ChatTranslatorStandalone',
  'translator.alphabet = ' + "'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'",
  'translator.relayCounter = translator.relayCounter or 0',
  'translator.channelRelayCounter = translator.channelRelayCounter or 0',
  'translator.appliedChatSequences = translator.appliedChatSequences or {}',
  'translator.appliedChannelSequences = translator.appliedChannelSequences or {}',
  'translator.pollTicks = translator.pollTicks or 0',
  '',
  'function translator.encode(input)',
  '\tlocal output = {}',
  '\tfor index = 1, #input, 3 do',
  '\t\tlocal byteOne = string.byte(input, index)',
  '\t\tlocal byteTwo = string.byte(input, index + 1)',
  '\t\tlocal byteThree = string.byte(input, index + 2)',
  '\t\tlocal chunk = byteOne * 65536 + (byteTwo or 0) * 256 + (byteThree or 0)',
  '\t\tlocal charFour = chunk % 64',
  '\t\tchunk = (chunk - charFour) / 64',
  '\t\tlocal charThree = chunk % 64',
  '\t\tchunk = (chunk - charThree) / 64',
  '\t\tlocal charTwo = chunk % 64',
  '\t\tchunk = (chunk - charTwo) / 64',
  '\t\tlocal charOne = chunk % 64',
  '\t\ttable.insert(output, string.sub(translator.alphabet, charOne + 1, charOne + 1))',
  '\t\ttable.insert(output, string.sub(translator.alphabet, charTwo + 1, charTwo + 1))',
  "\t\ttable.insert(output, byteTwo and string.sub(translator.alphabet, charThree + 1, charThree + 1) or '=')",
  "\t\ttable.insert(output, byteThree and string.sub(translator.alphabet, charFour + 1, charFour + 1) or '=')",
  '\tend',
  '\treturn table.concat(output)',
  'end',
  '',
  'function translator.decode(input)',
  '\tlocal charValues = {}',
  '\tfor index = 1, 64 do',
  '\t\tcharValues[string.sub(translator.alphabet, index, index)] = index - 1',
  '\tend',
  "\tinput = string.gsub(input, '=', '')",
  '\tlocal bitCount = 0',
  '\tlocal accumulator = 0',
  '\tlocal output = {}',
  '\tfor index = 1, #input do',
  '\t\tlocal value = charValues[string.sub(input, index, index)]',
  "\t\tif value == nil then return '' end",
  '\t\taccumulator = accumulator * 64 + value',
  '\t\tbitCount = bitCount + 6',
  '\t\tif bitCount >= 8 then',
  '\t\t\tbitCount = bitCount - 8',
  '\t\t\tlocal byteValue = math.floor(accumulator / (2 ^ bitCount))',
  '\t\t\taccumulator = accumulator % (2 ^ bitCount)',
  '\t\t\ttable.insert(output, string.char(byteValue))',
  '\t\tend',
  '\tend',
  '\treturn table.concat(output)',
  'end',
  '',
  'function translator.announce(message)',
  '\tpcall(function() Echo(message) end)',
  'end',
  '',
  'function ChatTranslatorApply(sequenceNumber, applyCallback)',
  '\tif translator.appliedChatSequences[sequenceNumber] then return end',
  '\ttranslator.appliedChatSequences[sequenceNumber] = true',
  '\tpcall(applyCallback)',
  'end',
  '',
  'function ChannelTranslatorApply(sequenceNumber, applyCallback)',
  '\tif translator.appliedChannelSequences[sequenceNumber] then return end',
  '\ttranslator.appliedChannelSequences[sequenceNumber] = true',
  '\tpcall(applyCallback)',
  'end',
  '',
  'function ChatTranslatorDeliver(originalEncoded, translatedEncoded)',
  '\tpcall(function()',
  '\t\tif not (GameChat and GameChat.gameChat) then return end',
  '\t\tlocal originalText = translator.decode(originalEncoded)',
  '\t\tlocal translatedText = translator.decode(translatedEncoded)',
  "\t\tif originalText == '' or translatedText == '' then return end",
  '\t\tlocal replacedCount = 0',
  '\t\tfor index = 1, #GameChat.gameChat do',
  '\t\t\tlocal chatEntry = GameChat.gameChat[index]',
  "\t\t\tlocal combined = tostring(chatEntry.prefix or '') .. tostring(chatEntry.message or '')",
  '\t\t\tif combined == originalText then',
  "\t\t\t\tlocal headEnd = string.find(combined, '%^%*: [^%^]*$')",
  '\t\t\t\tif headEnd then',
  '\t\t\t\t\tchatEntry.prefix = string.sub(combined, 1, headEnd + 3) .. translatedText',
  '\t\t\t\telse',
  '\t\t\t\t\tchatEntry.prefix = translatedText',
  '\t\t\t\tend',
  "\t\t\t\tchatEntry.message = ''",
  '\t\t\t\treplacedCount = replacedCount + 1',
  '\t\t\tend',
  '\t\tend',
  '\t\tif replacedCount > 0 then',
  '\t\t\tlocal currentLine = GameChat:BuildChatTable(nil)',
  '\t\t\tGameChat.TransferChatTable(GameChat, currentLine, 0)',
  '\t\t\tGameChat:UpdateChatScroller()',
  '\t\tend',
  "\t\ttranslator.announce('HONCHATDELIVERED|' .. tostring(replacedCount))",
  '\tend)',
  'end',
  '',
  'function ChannelTranslatorDeliver(prefixEncoded, messageEncoded, translatedEncoded)',
  '\tpcall(function()',
  '\t\tif not (Communicator and Communicator.channelHistories) then return end',
  '\t\tlocal originalPrefix = translator.decode(prefixEncoded)',
  '\t\tlocal originalMessage = translator.decode(messageEncoded)',
  '\t\tlocal translatedText = translator.decode(translatedEncoded)',
  "\t\tif translatedText == '' then return end",
  '\t\tlocal replacedCount = 0',
  '\t\tfor _, channelHistory in pairs(Communicator.channelHistories) do',
  '\t\t\tfor index = 1, #channelHistory do',
  '\t\t\t\tlocal entry = channelHistory[index]',
  '\t\t\t\tif entry.prefix == originalPrefix and entry.message == originalMessage then',
  '\t\t\t\t\tentry.message = translatedText',
  '\t\t\t\t\treplacedCount = replacedCount + 1',
  '\t\t\t\tend',
  '\t\t\tend',
  '\t\tend',
  '\t\tif replacedCount > 0 then',
  '\t\t\tpcall(function() Communicator:ReloadChannel() end)',
  '\t\tend',
  "\t\ttranslator.announce('HONCHANDELIVERED|' .. tostring(replacedCount))",
  '\tend)',
  'end',
  '',
  'function ChatTranslatorSend(encodedText, channelName)',
  '\tpcall(function()',
  '\t\tlocal messageText = translator.decode(encodedText)',
  "\t\tif messageText == '' then return end",
  "\t\tif channelName == 'team' then",
  '\t\t\tTeamChat(messageText)',
  '\t\telse',
  '\t\t\tAllChat(messageText)',
  '\t\tend',
  "\t\ttranslator.announce('HONCHATSENT|' .. tostring(channelName))",
  '\tend)',
  'end',
  '',
  'function translator.readInbox(inboxFileName)',
  '\tpcall(function()',
  '\t\tlocal canCheckFiles = Testing and Testing.FileExists',
  "\t\tif not canCheckFiles or Testing.FileExists('#/' .. inboxFileName) then",
  "\t\t\tpcall(function() runfile('#/' .. inboxFileName) end)",
  "\t\telseif canCheckFiles and Testing.FileExists('~/' .. inboxFileName) then",
  "\t\t\tpcall(function() runfile('~/' .. inboxFileName) end)",
  '\t\tend',
  '\tend)',
  'end',
  '',
  'function translator.pollOnce()',
  '\ttranslator.pollTicks = translator.pollTicks + 1',
  "\ttranslator.readInbox('ChatTranslatorInbox.lua')",
  "\ttranslator.readInbox('ChannelTranslatorInbox.lua')",
  '\tif translator.pollTicks % 30 == 0 then',
  "\t\ttranslator.announce('HONCHATSTANDALONEALIVE|' .. tostring(translator.pollTicks))",
  '\tend',
  'end',
  '',
  'function translator.startPollThread(contextName)',
  '\tif type(newthread) ~= ' + "'function'" + ' then',
  "\t\ttranslator.announce('HONCHATSTANDALONENOTHREAD|' .. tostring(contextName))",
  '\t\treturn false',
  '\tend',
  '\tlocal started = pcall(function()',
  '\t\tnewthread(function()',
  '\t\t\twhile true do',
  '\t\t\t\twait(300)',
  '\t\t\t\tpcall(translator.pollOnce)',
  '\t\t\tend',
  '\t\tend)',
  '\tend)',
  '\tif started then',
  "\t\ttranslator.announce('HONCHATSTANDALONEPOLL|' .. tostring(contextName))",
  '\telse',
  "\t\ttranslator.announce('HONCHATSTANDALONEPOLLFAILED|' .. tostring(contextName))",
  '\tend',
  '\treturn started',
  'end',
  '',
  'if GameChat and GameChat.AllChatMessages and not translator.gameChatWrapped then',
  '\ttranslator.gameChatWrapped = true',
  '\tlocal originalAllChatMessages = GameChat.AllChatMessages',
  '\tGameChat.AllChatMessages = function(self, messageType, channel, prefix, message, sender, senderName, entity, isMe, iconOverride)',
  '\t\tpcall(function()',
  "\t\t\tlocal relayText = tostring(prefix or '') .. tostring(message or '')",
  "\t\t\tif relayText ~= '' then",
  '\t\t\t\ttranslator.relayCounter = translator.relayCounter + 1',
  "\t\t\t\ttranslator.announce('HONCHATRELAY|' .. tostring(translator.relayCounter) .. '|' .. tostring(messageType) .. '|' .. translator.encode(tostring(senderName or '')) .. '|' .. translator.encode(relayText))",
  '\t\t\tend',
  '\t\tend)',
  '\t\treturn originalAllChatMessages(self, messageType, channel, prefix, message, sender, senderName, entity, isMe, iconOverride)',
  '\tend',
  "\ttranslator.announce('HONCHATSTANDALONEREADY|gamechat')",
  "\ttranslator.startPollThread('gamechat')",
  'end',
  '',
  'if Communicator and Communicator.AddMessage and not translator.communicatorWrapped then',
  '\ttranslator.communicatorWrapped = true',
  '\tlocal originalAddMessage = Communicator.AddMessage',
  '\tCommunicator.AddMessage = function(self, channelName, prefix, message, sender)',
  '\t\tpcall(function()',
  "\t\t\tlocal relayContent = tostring(prefix or '') .. tostring(message or '')",
  "\t\t\tif relayContent ~= '' then",
  '\t\t\t\ttranslator.channelRelayCounter = translator.channelRelayCounter + 1',
  "\t\t\t\ttranslator.announce('HONCHANRELAY|' .. tostring(translator.channelRelayCounter) .. '|' .. translator.encode(tostring(channelName or '')) .. '|' .. translator.encode(tostring(sender or '')) .. '|' .. translator.encode(tostring(prefix or '')) .. '|' .. translator.encode(tostring(message or '')))",
  '\t\t\tend',
  '\t\tend)',
  '\t\treturn originalAddMessage(self, channelName, prefix, message, sender)',
  '\tend',
  "\ttranslator.announce('HONCHATSTANDALONEREADY|communicator')",
  "\ttranslator.startPollThread('communicator')",
  'end',
  ''
]

